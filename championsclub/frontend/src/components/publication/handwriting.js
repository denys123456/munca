export function handwritingPaths(text) {
  let offset = 0
  return [...text].flatMap((letter) => {
    if (letter === ' ') { offset += 15; return [] }
    const glyph = glyphs[letter]
    if (!glyph) return []
    const item = { path: glyph[0], offset }
    offset += glyph[1] - 3
    return [item]
  })
}
