import { test, expect } from '@playwright/test'
import { readFileSync, existsSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { money, number, localDate } from '../src/lib/format.js'

const settingsFile = fileURLToPath(new URL('../../../.work/preview-settings.json', import.meta.url))
const local = existsSync(settingsFile) ? JSON.parse(readFileSync(settingsFile, 'utf8').trim()) : {}
const password = process.env.CHAMPIONSCLUB_DEMO_PASSWORD || local.password
const apiBase = process.env.PLAYWRIGHT_API_BASE_URL || local.api || 'http://127.0.0.1:8080'
const advisorEmail = process.env.CHAMPIONSCLUB_TEST_ADVISOR || 'jane.doe@championsclub.example'
const managerEmail = process.env.CHAMPIONSCLUB_TEST_MANAGER || 'alex.smith@championsclub.example'
const canMutate = process.env.CHAMPIONSCLUB_ALLOW_TEST_MUTATIONS === '1'
const artifacts = fileURLToPath(new URL('../artifacts/premium/', import.meta.url))
mkdirSync(artifacts, { recursive: true })

test.beforeAll(() => { if (!password) throw new Error('Set CHAMPIONSCLUB_DEMO_PASSWORD and a dedicated verification backend before running live tests.') })

async function apiLogin(request, email) {
  const response = await request.post(`${apiBase}/api/auth/login`, { data: { email, password } })
  expect(response.status()).toBe(200)
  return response.json()
}
async function get(request, auth, path) {
  const response = await request.get(`${apiBase}${path}`, { headers: { Authorization: `Bearer ${auth.accessToken}` } })
  expect(response.status()).toBe(200)
  return response.json()
}
async function login(page, email = advisorEmail) {
  await page.goto('/')
  await page.getByLabel('Email address', { exact: false }).fill(email)
  await page.getByLabel('Password', { exact: false }).fill(password)
  const response = page.waitForResponse(response => response.url().endsWith('/api/auth/login') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  const result = await response
  expect(result.status()).toBe(200)
  await expect(page.getByRole('heading', { name: 'Welcome back,', exact: false })).toBeVisible()
  await expect(page.locator('.kpi').first()).toBeVisible()
  return result.json()
}
async function navigate(page, title) {
  await page.locator('.sidebar nav').getByRole('link', { name: title, exact: true }).click()
  await expect(page.locator('main')).not.toContainText('This view could not be displayed')
}
async function screenshot(page, name) {
  await page.screenshot({ path: `${artifacts}${name}.png`, fullPage: true })
}

