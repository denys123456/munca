test('service error, empty results, session expiry and keyboard modal behavior', async ({ page }) => {
  await login(page)
  await page.route('**/api/products?**', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: 'Provider unavailable' }) }))
  await navigate(page, 'Product catalog')
  await expect(page.getByRole('alert')).toContainText('The service could not complete this request')
  await page.unroute('**/api/products?**')
  await page.getByRole('button', { name: 'Try again' }).click()
  await expect(page.getByRole('table')).toBeVisible()
  await page.getByRole('button', { name: 'View details' }).first().click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(page.getByRole('button', { name: 'View details' }).first()).toBeFocused()
  await page.getByRole('textbox', { name: 'Search products' }).fill('NO-PRODUCT-WITH-THIS-NAME')
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'No products found' })).toBeVisible()
  await screenshot(page, 'empty-state')
  await page.route('**/api/alerts?**', route => route.fulfill({ status: 401, contentType: 'application/json', body: JSON.stringify({ message: 'Access denied.' }) }))
  await navigate(page, 'Notifications')
  await expect(page.getByRole('button', { name: 'Sign in', exact: true })).toBeVisible()
  await expect(page.getByRole('status')).toContainText('Your session has expired')
})

