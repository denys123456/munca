test('real sales creation, conflict handling, cancellation, filters and pagination', async ({ page, request }) => {
  test.skip(!canMutate, 'Explicitly enable mutations against a dedicated verification database.')
  const auth = await login(page)
  const before = await get(request, auth, `/api/points/${auth.user.id}`)
  await navigate(page, 'Sales activity')
  await page.getByRole('button', { name: 'Record a sale', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.locator('summary').click()
  await dialog.getByRole('button', { name: 'Classic Financing', exact: true }).click()
  await dialog.getByLabel('Contract value (EUR)', { exact: false }).fill('1500.25')
  const reference = `UI-VERIFY-${Date.now()}`
  await dialog.getByLabel('External reference', { exact: false }).fill(reference)
  await screenshot(page, 'sale-form')
  const response = page.waitForResponse(response => response.url().endsWith('/api/sales') && response.request().method() === 'POST')
  await dialog.getByRole('button', { name: 'Record sale', exact: true }).click()
  const created = await response
  expect(created.status()).toBe(201)
  const sale = await created.json()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('row').filter({ hasText: reference })).toBeVisible()
  const after = await get(request, auth, `/api/points/${auth.user.id}`)
  expect(after.availablePoints).toBe(before.availablePoints + sale.awardedPoints)
  await page.getByRole('button', { name: 'Record a sale', exact: true }).click()
  await dialog.locator('summary').click()
  await dialog.getByRole('button', { name: 'Classic Financing', exact: true }).click()
  await dialog.getByLabel('Contract value (EUR)', { exact: false }).fill('1500.25')
  await dialog.getByLabel('External reference', { exact: false }).fill(reference)
  await dialog.getByRole('button', { name: 'Record sale', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('already exists')
  await expect(dialog.getByLabel('External reference', { exact: false })).toHaveValue(reference)
  await dialog.getByRole('button', { name: 'Close dialog' }).click()
  await page.getByRole('row').filter({ hasText: reference }).getByRole('button', { name: 'Cancel sale' }).click()
  await expect(dialog.getByRole('heading', { name: 'Cancel this sale?' })).toBeVisible()
  await screenshot(page, 'cancel-confirmation')
  await dialog.getByRole('button', { name: 'Confirm cancellation' }).click()
  await expect(page.getByRole('row').filter({ hasText: reference })).toContainText('Cancelled')
  const reverted = await get(request, auth, `/api/points/${auth.user.id}`)
  expect(reverted.availablePoints).toBe(before.availablePoints)
  await page.getByLabel('Status', { exact: true }).selectOption('CANCELLED')
  await page.getByRole('button', { name: 'Apply filters' }).click()
  await expect(page.locator('tbody .badge').first()).toHaveText('Cancelled')
  await page.getByRole('button', { name: 'Clear filters' }).click()
  await page.getByRole('button', { name: 'Next page' }).click()
  await expect(page.locator('.pagination')).toContainText('Page 2')
  await screenshot(page, 'sales-table')
})

