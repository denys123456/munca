test('reward redemption deducts once and preserves lifetime membership', async ({ page }) => {
  await start(page, 'jane-advisor', 'rewards')
  const fuel = page.locator('.reward-card').filter({ hasText: 'Premium Fuel Voucher' })
  await fuel.getByRole('button').click()
  await expect(page.getByRole('dialog')).toContainText('680')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.locator('.membership-balance')).toContainText('1,330')
  await fuel.getByRole('button').click()
  await page.getByRole('button', { name: 'Confirm redemption' }).dblclick()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('.membership-balance')).toContainText('680')
  await expect(fuel.getByRole('button')).toBeDisabled()
  const saved = await state(page)
  expect(saved.advisors[0].points).toBe(1330)
  expect(saved.advisors[0].availablePoints).toBe(680)
  expect(saved.redemptions.filter((item) => item.status === 'Submitted')).toHaveLength(1)
  await page.getByRole('button', { name: 'Travel', exact: true }).click()
  await expect(page.locator('.reward-card')).toHaveCount(1)
  await expect(page.locator('.reward-card button')).toBeDisabled()
  await page.reload()
  await expect(page.locator('.membership-balance')).toContainText('680')
})

