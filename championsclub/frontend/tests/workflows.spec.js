import { test, expect, start, navigate, state } from './helpers.js'

test('a new sale persists and updates performance, points and targets', async ({ page }) => {
  await start(page, 'alex-manager', 'dealership-activity')
  await page.getByRole('button', { name: 'Record sale', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await dialog.getByRole('combobox', { name: 'Advisor', exact: true }).selectOption('1')
  await dialog.getByRole('combobox', { name: 'Product', exact: true }).selectOption('Classic Financing')
  await dialog.getByLabel('Amount', { exact: true }).fill('10000')
  await dialog.getByLabel('Date', { exact: true }).fill('2026-09-10')
  await dialog.getByRole('button', { name: 'Record sale', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('status')).toContainText('Sale recorded')
  const saved = await state(page)
  expect(saved.dealership.monthlySales).toBe(322400)
  expect(saved.advisors[0].points).toBe(1450)
  expect(saved.targets.find((target) => target.advisorId === 1).actual).toBe(128500)
  await page.reload()
  await page.getByLabel('Search sales').fill('Classic')
  await expect(page.locator('.premium-table-row')).toHaveCount(2)
  await page.getByLabel('Search sales').fill('no matching sales')
  await expect(page.locator('.premium-table-row')).toHaveCount(0)
  await page.getByLabel('Search sales').fill('')
  await page.getByLabel('Filter product').selectOption('Service Protection')
  await expect(page.locator('.premium-table-row')).toHaveCount(2)
  await page.getByLabel('Filter product').selectOption('All')
  await page.getByRole('button', { name: 'Next', exact: true }).click()
  await expect(page.locator('.pagination')).toContainText('Page 2 of 2')
  await expect(page.getByRole('button', { name: 'Next', exact: true })).toBeDisabled()
})

test('advisor recording restricts the advisor and validates the amount', async ({ page }) => {
  await start(page, 'jane-advisor', 'sales-history')
  await expect(page.locator('.premium-table-row')).toHaveCount(2)
  await page.getByRole('button', { name: 'Record sale', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('combobox', { name: 'Advisor', exact: true }).locator('option')).toHaveCount(1)
  await page.getByRole('dialog').getByLabel('Amount', { exact: true }).fill('-1')
  await page.getByRole('dialog').getByRole('button', { name: 'Record sale' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  expect(await page.getByLabel('Amount', { exact: true }).evaluate((element) => element.validity.valid)).toBe(false)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Record sale', exact: true })).toBeFocused()
})

