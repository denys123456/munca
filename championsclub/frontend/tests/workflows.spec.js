test('account preferences and role routes remain independent', async ({ page }) => {
  await start(page, 'alex-manager', 'profile')
  await page.getByRole('button', { name: 'Edit preferences' }).click()
  await page.getByRole('combobox', { name: 'Notification digest', exact: true }).selectOption('Weekly')
  await page.getByRole('button', { name: 'Save preferences' }).click()
  await page.reload()
  await expect(page.locator('#workspace-content')).toContainText('Weekly')
  await changeAccount(page, 'jane-advisor')
  await navigate(page, 'profile')
  await expect(page.locator('.profile-hero')).toContainText('Jane Doe')
  await expect(page.locator('#workspace-content')).toContainText('Daily')
  await page.evaluate(() => { location.hash = '/workspace/admin-users' })
  await expect(page.locator('.operational-workspace')).toHaveAttribute('data-route', 'overview')
  await expect(page.getByRole('button', { name: 'Users', exact: true })).toHaveCount(0)
  await changeAccount(page, 'john-admin')
  await expect(page.locator('.operational-workspace')).toHaveAttribute('data-route', 'admin-overview')
  await expect(page.getByRole('button', { name: 'Users', exact: true })).toHaveCount(1)
})
